"""Example Python module to test prek and zuban setup."""


def add_numbers(a: int, b: int) -> int:
    """Add two numbers together.

    Args:
        a: First number
        b: Second number

    Returns:
        The sum of a and b
    """
    return a + b


def greet(name: str) -> str:
    """Generate a greeting message.

    Args:
        name: Name to greet

    Returns:
        A greeting string
    """
    return f"Hello, {name}!"
